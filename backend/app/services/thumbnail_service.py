"""Image thumbnail pipeline.

Thumbnails are generated by a dedicated background worker (never blocking
imports or API responses), cached on disk as `<asset-id>.jpg` with a sidecar
`<asset-id>.json` holding the source file fingerprint (size + mtime_ns).
When the source changes, the next request regenerates; repeated failures are
marked `failed` in the DB and are NOT retried until the source changes.
"""

from __future__ import annotations

import json
import os
import queue
import threading
from pathlib import Path

from PIL import Image, ImageOps
from sqlalchemy.orm import Session, sessionmaker

from backend.app.models.asset import Asset
from backend.app.services import media_service

THUMBNAIL_BOX = (512, 512)
JPEG_QUALITY = 85

_holder: dict[str, object] = {}


def bind_thumbnail_worker(session_factory: sessionmaker, thumbnail_dir: Path) -> None:
    _holder["factory"] = session_factory
    _holder["worker"] = ThumbnailWorker(Path(thumbnail_dir))
    _holder["dir"] = Path(thumbnail_dir)
    Path(thumbnail_dir).mkdir(parents=True, exist_ok=True)


def _parts() -> tuple[sessionmaker, "ThumbnailWorker", Path]:
    factory = _holder.get("factory")
    worker = _holder.get("worker")
    directory = _holder.get("dir")
    if not isinstance(factory, sessionmaker) or not isinstance(worker, ThumbnailWorker) or not isinstance(directory, Path):
        raise RuntimeError("thumbnail service is not bound")
    return factory, worker, directory


def enqueue_asset(asset_id: int) -> None:
    """Fire-and-forget enqueue; silently no-ops when the service is unbound."""
    try:
        _, worker, _ = _parts()
    except RuntimeError:
        return
    worker.submit(asset_id)


def thumbnail_file(asset_id: int) -> Path:
    _, _, directory = _parts()
    return directory / f"{asset_id}.jpg"


def _read_meta(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def get_thumbnail(db: Session, asset: Asset) -> Path | None:
    """Return a valid cached thumbnail, or None after (re-)enqueuing generation."""
    if asset.asset_type not in ("image", "video", "audio") or not asset.file_path:
        return None
    factory, worker, directory = _parts()
    thumb_path = directory / f"{asset.id}.jpg"
    meta = _read_meta(directory / f"{asset.id}.json")
    try:
        stat = os.stat(asset.file_path)
    except OSError:
        return None
    fingerprint = {"size": stat.st_size, "mtime_ns": stat.st_mtime_ns}
    matches = bool(
        meta
        and meta.get("size") == fingerprint["size"]
        and meta.get("mtime_ns") == fingerprint["mtime_ns"]
    )
    if matches and thumb_path.exists():
        if asset.thumbnail_status != "ready":
            asset.thumbnail_status = "ready"
            db.commit()
        return thumb_path
    if matches and (meta.get("failed") or meta.get("no_cover")):
        if asset.thumbnail_status != "ready" and meta.get("no_cover"):
            asset.thumbnail_status = "ready"
            db.commit()
        return None  # terminal for this source version; wait for a source change

    worker.submit(asset.id)
    return None


class ThumbnailWorker:
    def __init__(self, directory: Path) -> None:
        self._directory = directory
        self._queue: queue.Queue[int] = queue.Queue()
        self._queued: set[int] = set()
        self._lock = threading.Lock()
        self._thread: threading.Thread | None = None

    def submit(self, asset_id: int) -> None:
        with self._lock:
            if asset_id in self._queued:
                return
            self._queued.add(asset_id)
        self._ensure_started()
        self._queue.put(asset_id)

    def _ensure_started(self) -> None:
        with self._lock:
            if self._thread is not None and self._thread.is_alive():
                return
            self._thread = threading.Thread(
                target=self._run, daemon=True, name="ryan-dam-thumbnail-worker"
            )
            self._thread.start()

    def _run(self) -> None:
        while True:
            asset_id = self._queue.get()
            try:
                factory = _holder.get("factory")
                if isinstance(factory, sessionmaker):
                    _process_asset(factory, self._directory, asset_id)
            except Exception:  # noqa: BLE001 - worker must never die
                pass
            finally:
                with self._lock:
                    self._queued.discard(asset_id)
                self._queue.task_done()


def _process_asset(factory: sessionmaker, directory: Path, asset_id: int) -> None:
    with factory() as session:
        asset = session.get(Asset, asset_id)
        if asset is None or asset.asset_type not in ("image", "video", "audio") or not asset.file_path:
            return
        try:
            stat = os.stat(asset.file_path)
        except OSError:
            asset.thumbnail_status = "failed"
            _write_meta(directory, asset_id, {"failed": True})
            session.commit()
            return
        fingerprint = {"size": stat.st_size, "mtime_ns": stat.st_mtime_ns}
        destination = directory / f"{asset_id}.jpg"
        try:
            if asset.asset_type == "image":
                _render_image(asset.file_path, destination)
                meta = dict(fingerprint)
            else:
                meta = _render_media(asset, destination)
                meta.update(fingerprint)
        except Exception:  # noqa: BLE001 - any decode/save error marks failure
            asset.thumbnail_status = "failed"
            _write_meta(directory, asset_id, {**fingerprint, "failed": True})
            session.commit()
            return
        asset.thumbnail_status = "ready"
        _write_meta(directory, asset_id, meta)
        session.commit()


def _render_media(asset: Asset, destination: Path) -> dict:
    """Video: representative frame + duration/size. Audio: duration + optional cover."""
    probe = media_service.probe(asset.file_path)
    if probe is None:
        raise RuntimeError("ffprobe unavailable or media unreadable")
    if probe.get("duration_ms") is not None:
        asset.media_duration_ms = probe["duration_ms"]
    meta: dict = {}
    if asset.asset_type == "video":
        if not media_service.extract_frame(asset.file_path, destination):
            raise RuntimeError("frame extraction failed")
        asset.media_width = probe.get("width")
        asset.media_height = probe.get("height")
    else:
        if media_service.extract_cover(asset.file_path, destination):
            meta["cover"] = True
        else:
            meta["no_cover"] = True
    return meta


def _write_meta(directory: Path, asset_id: int, payload: dict) -> None:
    try:
        (directory / f"{asset_id}.json").write_text(
            json.dumps(payload, separators=(",", ":")), encoding="utf-8"
        )
    except OSError:
        pass


def _render_image(source_path: str, destination: Path) -> None:
    with Image.open(source_path) as image:
        image = ImageOps.exif_transpose(image)
        image.thumbnail(THUMBNAIL_BOX)
        if image.mode in ("RGBA", "LA", "P"):
            rgba = image.convert("RGBA")
            background = Image.new("RGB", rgba.size, (255, 255, 255))
            background.paste(rgba, mask=rgba.getchannel("A"))
            image = background
        elif image.mode != "RGB":
            image = image.convert("RGB")
        image.save(destination, "JPEG", quality=JPEG_QUALITY)
